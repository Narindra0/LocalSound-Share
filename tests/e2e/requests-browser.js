'use strict';
const assert = require('node:assert/strict');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const { createApp } = require('../../server');
const { coverPng } = require('../helpers/media-fixture');
class Capture {startSystemAudio(callback){this.timer=setInterval(()=>callback(Buffer.alloc(1920)),10)}stop(){clearInterval(this.timer)}}
(async()=>{
  let browser,update;
  const app=createApp({Capture,mediaInfo:{start(cb){update=cb},close(){}}});
  try{
    await new Promise(resolve=>app.server.listen(0,'0.0.0.0',resolve));app.control('play');
    browser=await chromium.launch({channel:'msedge',headless:true,args:['--mute-audio']});
    const context=await browser.newContext({viewport:{width:1366,height:768}});
    const host=await context.newPage(),listener=await context.newPage(),second=await context.newPage(),errors=[];
    for(const page of [host,listener,second])page.on('pageerror',err=>errors.push(err.message));
    const base='http://127.0.0.1:'+app.server.address().port,lan=app.status().urls[0]||base;
    await host.goto(base+'/host');await listener.goto(lan+'/listen');await second.goto(lan+'/listen');
    await listener.waitForFunction(()=>document.getElementById('connStatus').textContent==='Connecté');
    const generation=app.status().generation;
    update({available:true,sessions:[{title:'Musique en cours',artist:'Artiste',appId:'msedge.exe',playing:true,artworkBase64:coverPng().toString('base64')}]});
    await listener.waitForFunction(()=>document.body.dataset.artworkState==='ready');
    await listener.waitForFunction(()=>document.querySelector('.record-label').clientWidth/document.querySelector('.vinyl').clientWidth>.50);
    const ratio=await listener.evaluate(()=>{const label=document.querySelector('.record-label').getBoundingClientRect(),vinyl=document.querySelector('.vinyl').getBoundingClientRect();return label.width/vinyl.width});
    assert.ok(ratio>.48,'La pochette est lisible au centre du vinyle');
    await listener.setViewportSize({width:390,height:844});
    await listener.locator('#openRequestsModal').click();
    await listener.locator('#requestName').fill('Léa');
    await listener.locator('#requestTitle').fill('Mon prochain morceau <b>préféré</b>');
    await listener.locator('#requestUrl').fill('https://youtu.be/jNQXAC9IVRw');
    await listener.locator('#sendRequest').click();
    await listener.waitForFunction(()=>document.getElementById('requestsStatus').textContent.includes('Proposition envoyée'));
    await host.waitForFunction(()=>document.getElementById('requestCount').textContent==='1');
    await second.waitForFunction(()=>document.getElementById('requestCount').textContent==='1');
    assert.equal(await listener.locator('#requestsList b').count(),0);
    await listener.screenshot({path:path.resolve('artifacts/interface/request-listener-mobile.png')});
    await host.locator('#openRequestsModal').click();
    await host.getByRole('button',{name:'Accepter',exact:true}).click();
    await listener.waitForFunction(()=>document.querySelector('#requestsList .request-badge')?.textContent==='À écouter');
    const link=host.getByRole('link',{name:'Ouvrir YouTube'});
    assert.equal(await link.getAttribute('href'),'https://www.youtube.com/watch?v=jNQXAC9IVRw');
    await host.screenshot({path:path.resolve('artifacts/interface/request-host-desktop.png')});
    await host.getByRole('button',{name:'Marquer comme joué'}).click();
    await listener.waitForFunction(()=>!document.getElementById('requestsHistory').hidden);
    assert.equal(await listener.locator('#requestsHistoryList .request-badge').textContent(),'Joué');
    assert.equal(app.status().playing,true);assert.equal(app.status().generation,generation);
    await listener.locator('#closeRequestsModal').click();
    await listener.reload();await listener.locator('#openRequestsModal').click();
    assert.equal(await listener.locator('#requestName').inputValue(),'Léa');
    await listener.locator('#closeRequestsModal').click();
    await host.locator('#closeRequestsModal').click();await host.locator('#openSharingModal').click();
    await host.locator('#metadataSettings > summary').click();
    await host.locator('#artworkStatus').scrollIntoViewIfNeeded();
    assert.match(await host.locator('#artworkStatus').textContent(),/chargée/);
    update({available:true,sessions:[]});
    await host.waitForFunction(()=>document.body.dataset.artworkState==='missing');
    assert.match(await host.locator('#artworkStatus').textContent(),/Aucune pochette/);
    assert.deepEqual(errors,[]);
    console.log('Demandes : auditeur LAN mobile → hôte → acceptation → joué, mises à jour chez deux auditeurs, miniature agrandie et état explicite — OK');
  }finally{await browser?.close();await app.close()}
})().catch(err=>{console.error(err);process.exitCode=1});
